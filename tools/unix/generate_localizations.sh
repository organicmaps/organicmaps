#!/bin/bash
set -e -u

# Prevent python from generating compiled *.pyc files
export PYTHONDONTWRITEBYTECODE=1

OMIM_PATH="${OMIM_PATH:-$(dirname "$0")/../..}"
OMIM_PATH=$(realpath $OMIM_PATH)
DATA_PATH="${DATA_PATH:-$OMIM_PATH/data}"


function GenerateStringResource() {
  strings_file=$1
  output_prefix=$2
  format=$3
  tags=$4
  filename=${5:-}
  args=${@:6}
  include=translated

  if [[ $format == apple* ]]
  then
    # Apple strings file should fallback to English in case of missing translation.
    include=all
  fi

  if [[ $format == jquery* ]]
  then
    # sound-strings and countries-strings files should fallback to English in case of missing translation.
    include=all
  fi

  if [ -z "${tags}" ]; then
      tags=''
  else
      tags="--tags $tags"
  fi

  if [ -z "${filename}" ]; then
      filename=''
  else
      filename="--file-name $filename"
  fi

  echo
  echo "Building strings for '$format' and prefix '$output_prefix'"

  # Run script to build string resource
  python3 "$OMIM_PATH/tools/python/twine/python_twine/twine_cli.py" generate-all-localization-files \
    $OMIM_PATH/data/strings/$strings_file \
    $OMIM_PATH/$output_prefix \
    -f $format --include $include \
    $filename $tags \
    $args
}

# Keep the per-app language picker in sync with the packaged app languages.
python3 - "$OMIM_PATH/android" <<'PY'
import sys
from pathlib import Path
from xml.etree import ElementTree as ET

android_path = Path(sys.argv[1])
property_line = next(line for line in (android_path / "gradle.properties").read_text(encoding="utf-8").splitlines()
                     if line.startswith("supportedLocalizations="))
locales = [locale.strip().replace("_", "-") for locale in property_line.partition("=")[2].split(",")]
locales.remove("en")
locales.insert(0, "en")

namespace = "http://schemas.android.com/apk/res/android"
ET.register_namespace("android", namespace)
config = ET.Element("locale-config")
for locale in locales:
    ET.SubElement(config, "locale", {f"{{{namespace}}}name": locale})
ET.indent(config, space="    ")
xml = ('<?xml version="1.0" encoding="utf-8"?>\n'
       '<!-- Generated by tools/unix/generate_localizations.sh from android/gradle.properties. -->\n'
       + ET.tostring(config, encoding="unicode") + "\n")
(android_path / "app/src/main/res/xml/locales_config.xml").write_text(xml, encoding="utf-8")
PY

# Generate Android strings
GenerateStringResource "strings.txt" android/app/src/main/res android android-app ""
GenerateStringResource "strings.txt" android/sdk/src/main/res android android-sdk ""
GenerateStringResource "strings.txt" android/libs/car/src/main/res android android-libs-car ""
GenerateStringResource "strings.txt" android/libs/downloader/src/main/res android android-libs-downloader ""
GenerateStringResource "strings.txt" android/libs/routing/src/main/res android android-libs-routing ""
GenerateStringResource "strings.txt" android/wear/src/main/res android android-wear "wear_strings.xml"

# Generate iPhone strings
GenerateStringResource "strings.txt" iphone/Maps/LocalizedStrings apple apple-maps ""
GenerateStringResource "strings.txt" iphone/Maps/LocalizedStrings apple-plural apple-maps ""
GenerateStringResource "strings.txt" iphone/Maps/LocalizedStrings apple apple-infoplist "InfoPlist.strings"

# Generate Android types strings
GenerateStringResource "types_strings.txt" android/sdk/src/main/res android "" types_strings.xml

# Generate iPhone types strings
GenerateStringResource "types_strings.txt" iphone/Maps/LocalizedStrings apple "" LocalizableTypes.strings

# Generate sound strings
GenerateStringResource "sound.txt" data/sound-strings jquery ""
